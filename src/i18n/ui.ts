export type UIKey = keyof (typeof ui)['en'];

/** Extract locale from a URL pathname (e.g. /es/blog -> 'es'). */
export function getLangFromUrl(url: URL): Locale {
  const [, first] = url.pathname.split('/');
  if ((locales as readonly string[]).includes(first)) return first as Locale;
  return defaultLocale;
}

/** Translator bound to a locale, falling back to English. */
export function useTranslations(lang: Locale) {
  return function t(key: UIKey): string {
    return (ui[lang] as Record<UIKey, string>)[key] ?? ui.en[key];
  };
}

/** Prefix a root-relative path with the locale (no prefix for the default). */
export function localizePath(lang: Locale, path: string): string {
  if (lang === defaultLocale) return path;
  return `/${lang}${path === '/' ? '' : path}`;
}

